--Q1. Create a table named students with:
-- Column	Data type
-- id	INT
-- name	VARCHAR(100)
-- age	INT
-- city	VARCHAR(50)

CREATE TABLE student(
	id INT,
	name VARCHAR(100),
	age INT,
	city VARCHAR(50)
);

-- Q2. Create a table named employees with:
-- Column	Data type
-- id	INT
-- name	VARCHAR(100)
-- salary	INT
-- email	VARCHAR(100)
-- department	VARCHAR(50)

CREATE TABLE employees(
	id INT,
	name VARCHAR(100),
	salary INT,
	email VARCHAR(100),
	department VARCHAR(50)
	);
	